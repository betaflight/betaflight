#define DEFIO_TAG_PIN_REL(tag) ((tag) & DEFIO_PIN_BITMASK)

#define DEFIO_TAG_GPIOID(tag) \
({ \
    uint8_t port = DEFIO_TAG_GPIOID_REL(tag); \
    uint8_t pin = ((tag) & DEFIO_PIN_BITMASK); \
    if (port > DEFIO_GPIOID__F) { \
        port = 'x' - 'a'; \
        if (pin > 7) \
            port++; \
        if (pin > 15) \
            port++; \
    } \
    port; \
})

#define DEFIO_TAG_PIN(tag) ({\
                                uint8_t port = DEFIO_TAG_GPIOID_REL(tag); \
                                uint8_t pin = DEFIO_TAG_PIN_REL(tag); \
                                if (port > DEFIO_GPIOID__F) {\
                                   pin %= 8; \
                                } \
                                pin;\
                            })
